#!/usr/bin/env node
// Compiles the externally-owned ACC source into the gitignored local
// artefact directory and regenerates the committed binding manifest —
// including per-file content hashes (FS-0.2 T1; architecture §8 decision 2;
// ADR 0004). Compilation is deterministic for a given source and toolchain,
// so the committed hashes are re-derivable by anyone and `--check` can
// recompile and compare. The pin stays provisional until the contract team
// publishes an official versioned artefact
// (https://github.com/midnightntwrk/passport/issues/116). Prover keys are
// large and public; they stay in the artefact directory, addressed by
// keyLocation, never committed (provider-integration §5.1, §6).
//
// Usage:
//   node scripts/build-acc-artefact.mjs           # compile + write manifest
//   node scripts/build-acc-artefact.mjs --check   # recompile + fail on any divergence
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE =
  process.env.MN_PASSPORT_ACC_SOURCE ??
  '../passport/experiments/account-custody-prototype/contracts/account.compact';
const ARTEFACT_DIR = 'packages/contract/artefact';
const MANIFEST_PATH = 'packages/contract/src/manifest.generated.ts';
// The generated module and contract-info are consumed bytes too — hashed
// alongside every circuit's ZKIR (text and binary) and keys.
const MODULE_FILES = ['contract/index.js', 'contract/index.d.ts', 'compiler/contract-info.json'];
const CHECK = process.argv.includes('--check');

/** @param {string} path */
const sha256 = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');

/** @param {string} message @returns {never} */
function fail(message) {
  console.error(message);
  process.exit(1);
}

if (!existsSync(SOURCE)) {
  fail(`Source missing — no ACC source at ${SOURCE}; set MN_PASSPORT_ACC_SOURCE (FS-0.2 D-6).`);
}

console.log(`Compiling ${SOURCE} → ${ARTEFACT_DIR} (this takes ~30 s)…`);
execFileSync('compact', ['compile', SOURCE, ARTEFACT_DIR], { stdio: 'inherit' });

const cliVersion = execFileSync('compact', ['--version'], { encoding: 'utf8' }).trim();
const info = JSON.parse(readFileSync(join(ARTEFACT_DIR, 'compiler', 'contract-info.json'), 'utf8'));

// The pin is human-owned: carried forward from the committed manifest so a
// recompile never silently rebrands the binding. Bump it deliberately.
let bindingVersion = '0.0.0-prototype.1';
if (existsSync(MANIFEST_PATH)) {
  const m = readFileSync(MANIFEST_PATH, 'utf8').match(/BINDING_VERSION = '([^']+)'/);
  if (!m) fail(`Pin unreadable — ${MANIFEST_PATH} exists but carries no BINDING_VERSION.`);
  bindingVersion = m[1] ?? bindingVersion;
}

/** @type {Record<string, object>} */
const circuits = {};
for (const circuit of [...info.circuits].sort((a, b) => a.name.localeCompare(b.name))) {
  circuits[circuit.name] = circuit.proof
    ? {
        pure: circuit.pure,
        proof: true,
        // An extension-free, circuit-scoped reference: ZK-config resolvers
        // supply the layout (keys/, zkir/) and suffixes themselves
        // (provider-integration §5.1, §6).
        keyLocation: `acc/${bindingVersion}/${circuit.name}`,
        hashes: {
          zkir: sha256(join(ARTEFACT_DIR, 'zkir', `${circuit.name}.zkir`)),
          bzkir: sha256(join(ARTEFACT_DIR, 'zkir', `${circuit.name}.bzkir`)),
          verifierKey: sha256(join(ARTEFACT_DIR, 'keys', `${circuit.name}.verifier`)),
          proverKey: sha256(join(ARTEFACT_DIR, 'keys', `${circuit.name}.prover`)),
        },
      }
    : { pure: circuit.pure, proof: false };
}

const manifest = {
  bindingVersion,
  // [PROVISIONAL] — an SDK-assigned pin over the unversioned prototype,
  // hashes ours until the contract team publishes theirs (passport#116).
  provisional: true,
  source: { path: SOURCE, sha256: sha256(SOURCE) },
  toolchain: {
    cliVersion,
    compilerVersion: info['compiler-version'],
    languageVersion: info['language-version'],
    runtimeVersion: info['runtime-version'],
  },
  moduleHashes: Object.fromEntries(
    MODULE_FILES.map((rel) => [rel, sha256(join(ARTEFACT_DIR, rel))]),
  ),
  circuits,
};

const generated = `// GENERATED by scripts/build-acc-artefact.mjs — do not edit by hand.
// The committed pin of the externally-owned ACC artefact (FS-0.2; the
// binding axis, architecture §4.6; integrity model per ADR 0004 —
// compilation is deterministic, so these hashes are re-derivable from the
// pinned source and toolchain). The circuit table is the artefact's
// inventory, not the supported caller surface — callers are scoped by the
// spec (deploy only at T2). Regenerate: pnpm run build:artefact.

export const BINDING_VERSION = '${manifest.bindingVersion}';

export interface CircuitHashes {
  readonly zkir: string;
  readonly bzkir: string;
  readonly verifierKey: string;
  readonly proverKey: string;
}

export interface CircuitPin {
  readonly pure: boolean;
  readonly proof: boolean;
  readonly keyLocation?: string;
  readonly hashes?: CircuitHashes;
}

export interface AccManifest {
  readonly bindingVersion: string;
  readonly provisional: boolean;
  readonly source: { readonly path: string; readonly sha256: string };
  readonly toolchain: {
    readonly cliVersion: string;
    readonly compilerVersion: string;
    readonly languageVersion: string;
    readonly runtimeVersion: string;
  };
  readonly moduleHashes: Readonly<Record<string, string>>;
  readonly circuits: Readonly<Record<string, CircuitPin>>;
}

export const ACC_MANIFEST: AccManifest = ${JSON.stringify(manifest, null, 2)};
`;

// The committed file is Prettier-formatted (the format gate runs on it), so
// the generator must emit exactly what Prettier would — format the text
// before writing or comparing, or --check false-drifts on style alone.
// (Exactly the mistake behind ADR 0003's false finding.)
const formatted = execFileSync('pnpm', ['exec', 'prettier', '--stdin-filepath', MANIFEST_PATH], {
  encoding: 'utf8',
  input: generated,
});

if (CHECK) {
  const committed = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, 'utf8') : '';
  if (committed !== formatted) {
    fail(
      'Binding drift — a fresh compile does not reproduce the committed manifest: the source, ' +
        'toolchain, circuit table, or artefact bytes changed. If intended, regenerate with ' +
        '`pnpm run build:artefact` and bump BINDING_VERSION deliberately (ADR 0004).',
    );
  }
  console.log(`Binding ${bindingVersion} verified — a fresh compile reproduces the committed pin.`);
} else {
  writeFileSync(MANIFEST_PATH, formatted);
  console.log(
    `Manifest written — binding ${bindingVersion}, ${Object.keys(circuits).length} circuits, hashes committed.`,
  );
}
